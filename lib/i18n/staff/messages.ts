export function translateMessage(locale: Locale, message: string | null | undefined) {
  if (!message || locale === "en") {
    return message ?? "";
  }

  if (EXACT[message]) {
    return EXACT[message];
  }

  for (const [pattern, render] of PATTERNS) {
    const match = message.match(pattern);

    if (match) {
      return render(match);
    }
  }

  return message;
}
