// Writes docs/schema.md: every table, column, type and foreign key of the
// public schema, read from lib/supabase/database.types.ts (which
// `npm run types:supabase` generates from the local database). No database
// is needed, so CI can check that the doc is up to date.
//
//   node scripts/gen-schema-doc.mjs           write docs/schema.md
//   node scripts/gen-schema-doc.mjs --check   fail if docs/schema.md is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const typesPath = join(root, "lib/supabase/database.types.ts");
const dataModelPath = join(root, "docs/data-model.md");
export const schemaDocPath = join(root, "docs/schema.md");

function members(typeLiteral) {
  return ts.isTypeLiteralNode(typeLiteral) ? typeLiteral.members.filter(ts.isPropertySignature) : [];
}

function memberNamed(typeLiteral, name) {
  return members(typeLiteral).find((member) => member.name.getText() === name)?.type;
}

function typeText(node) {
  // Collapse whitespace so multi-line types fit in one table cell.
  return node.getText().replace(/\s+/g, " ").trim();
}

function cell(text) {
  return text.replace(/\|/g, "\\|");
}

/** Column type without "| null", and whether null is allowed. */
function splitNull(text) {
  const parts = text.split(" | ").map((part) => part.trim());
  const nullable = parts.includes("null");
  return { nullable, type: parts.filter((part) => part !== "null").join(" | ") };
}

function readRelationships(tupleType) {
  if (!tupleType || !ts.isTupleTypeNode(tupleType)) {
    return [];
  }

  return tupleType.elements.map((element) => {
    const field = (name) => {
      const value = memberNamed(element, name);
      return value ? typeText(value).replace(/"/g, "") : "";
    };
    const list = (name) => field(name).replace(/^\[|\]$/g, "").split(",").map((s) => s.trim()).filter(Boolean);

    return {
      columns: list("columns"),
      name: field("foreignKeyName"),
      oneToOne: field("isOneToOne") === "true",
      referencedColumns: list("referencedColumns"),
      referencedRelation: field("referencedRelation"),
    };
  });
}

/** One-line purpose of each table, from the Core Tables list in data-model.md. */
function readPurposes() {
  const purposes = new Map();
  const text = readFileSync(dataModelPath, "utf8");

  for (const match of text.matchAll(/^\| \[([a-z_]+)\]\(#[a-z_]+\) \| (.+?) \|\s*$/gm)) {
    purposes.set(match[1], match[2].trim());
  }

  return purposes;
}

export function buildSchemaDoc() {
  const source = ts.createSourceFile(
    typesPath,
    readFileSync(typesPath, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const database = source.statements.find(
    (statement) => ts.isTypeAliasDeclaration(statement) && statement.name.text === "Database",
  );

  if (!database) {
    throw new Error("Database type not found in database.types.ts");
  }

  const pub = memberNamed(database.type, "public");
  const tables = members(memberNamed(pub, "Tables")).sort((a, b) =>
    a.name.getText().localeCompare(b.name.getText()),
  );
  const functions = members(memberNamed(pub, "Functions")).sort((a, b) =>
    a.name.getText().localeCompare(b.name.getText()),
  );
  const purposes = readPurposes();
  const out = [];

  out.push(
    "---",
    "generated: true",
    "source: lib/supabase/database.types.ts",
    "---",
    "",
    "# Schema Reference",
    "",
    "> Generated by `node scripts/gen-schema-doc.mjs` from `lib/supabase/database.types.ts`.",
    "> Do not edit by hand: change a migration, run `npm run types:supabase` (it regenerates this file), and commit both.",
    "> What each table is for and how they relate: [data-model.md](data-model.md). Access rules: [rls-policies.md](rls-policies.md).",
    "",
    "Legend: **null** = column may be null · **default** = the database fills it when an insert leaves it out · **FK** = foreign key.",
    "Types are the TypeScript types the app sees: `string` also covers `uuid`, `text`, `date` and `timestamptz`; the exact SQL type is in `supabase/migrations/`.",
    "",
    "## Tables",
    "",
    "| Table | Columns | Purpose |",
    "| --- | ---: | --- |",
  );

  for (const table of tables) {
    const name = table.name.getText();
    const columns = members(memberNamed(table.type, "Row")).length;
    out.push(`| [${name}](#${name}) | ${columns} | ${cell(purposes.get(name) ?? "")} |`);
  }

  for (const table of tables) {
    const name = table.name.getText();
    const row = members(memberNamed(table.type, "Row"));
    const insert = new Map(
      members(memberNamed(table.type, "Insert")).map((member) => [
        member.name.getText(),
        Boolean(member.questionToken),
      ]),
    );
    const relationships = readRelationships(memberNamed(table.type, "Relationships"));
    const fkByColumn = new Map();

    for (const relationship of relationships) {
      relationship.columns.forEach((column, index) => {
        const target = `${relationship.referencedRelation}.${relationship.referencedColumns[index] ?? "id"}`;
        fkByColumn.set(column, [...(fkByColumn.get(column) ?? []), target]);
      });
    }

    out.push("", `## ${name}`, "");

    if (purposes.has(name)) {
      out.push(`${purposes.get(name)} More in [data-model.md](data-model.md#${name}).`, "");
    }

    out.push("| Column | Type | Null | Default | FK |", "| --- | --- | :---: | :---: | --- |");

    for (const column of row) {
      const columnName = column.name.getText();
      const { nullable, type } = splitNull(typeText(column.type));
      const optional = insert.get(columnName) ?? false;
      const fk = (fkByColumn.get(columnName) ?? [])
        .map((target) => {
          const [table] = target.split(".");
          return `[${target}](#${table})`;
        })
        .join(", ");

      out.push(
        `| \`${columnName}\` | \`${cell(type)}\` | ${nullable ? "null" : ""} | ${optional && !nullable ? "default" : ""} | ${fk} |`,
      );
    }
  }

  out.push(
    "",
    "## Database Functions",
    "",
    "Called with `supabase.rpc(name, args)`. Rules and permissions: [rls-policies.md](rls-policies.md).",
    "",
    "| Function | Args | Returns |",
    "| --- | --- | --- |",
  );

  for (const fn of functions) {
    const args = memberNamed(fn.type, "Args");
    const returns = memberNamed(fn.type, "Returns");
    const argText =
      !args || args.kind === ts.SyntaxKind.NeverKeyword
        ? ""
        : members(args)
            .map((arg) => `${arg.name.getText()}${arg.questionToken ? "?" : ""}: ${typeText(arg.type)}`)
            .join(", ");

    out.push(
      `| \`${fn.name.getText()}\` | ${argText ? `\`${cell(argText)}\`` : ""} | ${returns ? `\`${cell(typeText(returns))}\`` : ""} |`,
    );
  }

  return `${out.join("\n")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const doc = buildSchemaDoc();

  if (process.argv.includes("--check")) {
    const current = readFileSync(schemaDocPath, "utf8").replace(/\r\n/g, "\n");

    if (current !== doc) {
      console.error("docs/schema.md is out of date. Run: node scripts/gen-schema-doc.mjs");
      process.exit(1);
    }

    console.log("docs/schema.md is up to date.");
  } else {
    writeFileSync(schemaDocPath, doc);
    console.log(`Wrote ${schemaDocPath}`);
  }
}
